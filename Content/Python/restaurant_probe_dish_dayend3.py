# -*- coding: utf-8 -*-
"""Probe pay B defaults, BeginEat linear then-chain, add_member_variable API."""
import unreal, json, inspect
bel=unreal.BlueprintEditorLibrary
eas=unreal.EditorAssetLibrary
R={}

def title(n):
    try: return str(bel.get_node_title(n))
    except: return n.get_class().get_name()

def find_pin(node, substr, direction=None):
    if not node: return None
    substr=substr.lower()
    for p in bel.list_all_pins(node):
        if substr in str(p.get_pin_name()).lower():
            if direction is None or direction.lower() in str(p.get_pin_direction()).lower():
                return p
    return None

def pin_dump(p):
    if not p: return None
    d={"name":str(p.get_pin_name())}
    for fn in ("get_default_as_string","get_default_value","get_pin_value"):
        if hasattr(p,fn):
            try: d[fn]=str(getattr(p,fn)())
            except Exception as e: d[fn]="ERR:"+str(e)[:40]
    try: d["default_value"]=str(p.default_value)
    except Exception as e: d["default_value"]="ERR:"+str(e)[:40]
    try: d["autogen"]=str(p.get_editor_property("autogenerated_default_value"))
    except: pass
    try: d["defprop"]=str(p.get_editor_property("default_value"))
    except: pass
    return d

def find_custom(ge,name):
    for n in ge.list_all_nodes():
        if n.get_class().get_name()=="K2Node_CustomEvent" and title(n)==name:
            return n
    return None

def linear_then(ev,limit=20):
    out=[]; cur=ev
    for _ in range(limit):
        out.append(title(cur))
        tp=find_pin(cur,"then","Output")
        if not tp: break
        links=tp.list_connected_pins() or []
        if not links: 
            out.append("<<END>>"); break
        cur=links[0].get_owning_node()
    return out

mbp=eas.load_asset("/Game/Farm/Restaurant/BP_RestaurantManager")
tbp=eas.load_asset("/Game/Farm/Restaurant/BP_RestaurantTable")
mge=unreal.BlueprintGraphEditor.get_graph_editor(bel.find_event_graph(mbp))
tge=unreal.BlueprintGraphEditor.get_graph_editor(bel.find_event_graph(tbp))

for evn in ("OnGuestPaidSalad","OnGuestPaidStew"):
    ev=find_custom(mge,evn)
    # find float+float after event
    cur=ev
    for _ in range(10):
        tp=find_pin(cur,"then","Output")
        if not tp or not tp.list_connected_pins(): break
        cur=tp.list_connected_pins()[0].get_owning_node()
        if "float + float" in title(cur) or title(cur)=="Set RestaurantMoney":
            # if Set, look at connected add
            if title(cur)=="Set RestaurantMoney":
                vp=find_pin(cur,"RestaurantMoney","Input")
                for c in (vp.list_connected_pins() or []):
                    addn=c.get_owning_node()
                    R[evn+"_add"]=title(addn)
                    R[evn+"_B"]=pin_dump(find_pin(addn,"B","Input"))
                    R[evn+"_A"]=pin_dump(find_pin(addn,"A","Input"))
            else:
                R[evn+"_add"]=title(cur)
                R[evn+"_B"]=pin_dump(find_pin(cur,"B","Input"))
                R[evn+"_A"]=pin_dump(find_pin(cur,"A","Input"))
            break

R["BeginEat_linear"]=linear_then(find_custom(tge,"BeginEat"))
R["ClearSeat_linear"]=linear_then(find_custom(tge,"ClearSeat"))

# add_member_variable signature
for name in ("add_member_variable","AddMemberVariable","get_new_variables"):
    if hasattr(bel,name):
        try: R["api_"+name]=str(inspect.signature(getattr(bel,name)))
        except: R["api_"+name]="exists"

# Check if ServedCount already
gets=[title(n) for n in mge.list_all_nodes() if "Served" in title(n) or "DayEarn" in title(n)]
R["served_nodes"]=gets

# GrantMoney amounts on character
cbp=eas.load_asset("/Game/TopDown/Blueprints/BP_TopDownCharacter")
cge=unreal.BlueprintGraphEditor.get_graph_editor(bel.find_event_graph(cbp))
for evn in ("GrantMoney_Salad","GrantMoney_Stew"):
    ev=find_custom(cge,evn)
    R[evn+"_linear"]=linear_then(ev) if ev else None
    # find add coins B
    if ev:
        for n_title in linear_then(ev,15):
            pass
        cur=ev
        for _ in range(15):
            tp=find_pin(cur,"then","Output")
            if not tp or not tp.list_connected_pins(): break
            cur=tp.list_connected_pins()[0].get_owning_node()
            if "float + float" in title(cur) or "int + int" in title(cur) or "+" in title(cur):
                R[evn+"_addB"]=pin_dump(find_pin(cur,"B","Input"))
                break

# OrderPrice defaults in TrySeat
for n in tge.list_all_nodes():
    if title(n)=="Set OrderPrice":
        R.setdefault("order_prices",[]).append(pin_dump(find_pin(n,"OrderPrice","Input")))

