# -*- coding: utf-8 -*-
"""Dump Equal B raw + VisualizeCell state switches; check enum entries via export."""
import unreal
bel = unreal.BlueprintEditorLibrary
MGR = "/Game/Farm/Grid/BP_GridManager"

def log(m):
    unreal.log("[P4] " + str(m)); print("[P4] " + str(m))

def title(n):
    try: return str(bel.get_node_title(n))
    except: return n.get_class().get_name()

bp = unreal.load_asset(MGR)

# Export enum text
try:
    txt = unreal.EditorAssetLibrary.export_text(unreal.load_asset("/Game/Farm/Grid/E_PlotState"))
    log("enum export len=" + str(len(txt) if txt else 0))
    if txt:
        log("enum export snippet=" + str(txt)[:2000])
except Exception as ex:
    log("export " + str(ex))

# Try reading .uasset via AssetRegistry tags
try:
    e = unreal.load_asset("/Game/Farm/Grid/E_PlotState")
    # serialize names from generated enum
    gen = e
    log("enum full=" + e.get_full_name())
    # Use DataTable? No.
    # Try unreal.load_object for Enum
    en = unreal.find_object(None, "/Game/Farm/Grid/E_PlotState.E_PlotState")
    log("find_object=" + str(en))
except Exception as ex:
    log(str(ex))

# Dump Equal B default as default_value / autogenerated
for fname in ("GrowCell", "PlantCell", "WaterCell", "HarvestCell"):
    ge = unreal.BlueprintGraphEditor.get_graph_editor(bel.find_graph(bp, fname))
    for n in ge.list_all_nodes():
        t = title(n)
        if "Equal" in t.lower():
            for p in bel.list_all_pins(n):
                if str(p.get_pin_name()) == "B":
                    attrs = []
                    for meth in ("get_pin_value", "get_default_as_string", "get_default_value", "has_any_connections"):
                        if hasattr(p, meth):
                            try:
                                attrs.append("{}={!r}".format(meth, getattr(p, meth)()))
                            except Exception as ex:
                                attrs.append("{}=ERR:{}".format(meth, ex))
                    log("{} Equal.B {}".format(fname, attrs))

# VisualizeCell: look for Switch / Branch on State
ge = unreal.BlueprintGraphEditor.get_graph_editor(bel.find_graph(bp, "VisualizeCell"))
log("VisualizeCell nodes=" + str(len(list(ge.list_all_nodes()))))
for n in ge.list_all_nodes():
    t = title(n)
    cls = n.get_class().get_name()
    if "Switch" in t or "Switch" in cls or "Branch" in t or "Equal" in t.lower() or "Spawn" in t or "Set" in t:
        log("VIZ {} [{}]".format(t, cls))
        for p in bel.list_all_pins(n):
            try: v = p.get_pin_value()
            except: v = "?"
            cps = [(title(c.get_owning_node()), str(c.get_pin_name())) for c in p.list_connected_pins()]
            pn = str(p.get_pin_name())
            if cps or pn.lower() in ("execute","then","else","selection","a","b","item","state","returnvalue") or "case" in pn.lower():
                log("  {}.{}={!r} -> {}".format(t, pn, v, cps))
